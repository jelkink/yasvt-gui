#!/usr/bin/env python3
"""Regenerates src/hanzi_table.c: character-level traditional <-> simplified tables from OpenCC."""
import sys
import opencc

RANGES = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x2FA1F)]


def table(config):
    converter = opencc.OpenCC(config)
    entries = []
    for low, high in RANGES:
        for cp in range(low, high + 1):
            converted = converter.convert(chr(cp))
            if len(converted) == 1 and converted != chr(cp):
                entries.append((cp, ord(converted)))
    return entries


out = sys.stdout
out.write("/* Generated by tools/gen_hanzi.py; do not edit. */\n")
out.write('#include "hanzi_table.h"\n')
for name, config in (("t2s", "t2s.json"), ("s2t", "s2t.json")):
    entries = table(config)
    out.write(f"\nconst HanziEntry hanzi_{name}[] = {{\n")
    for source, target in entries:
        out.write(f"    {{0x{source:X}, 0x{target:X}}},\n")
    out.write("};\n")
    out.write(f"const unsigned hanzi_{name}_count = {len(entries)};\n")
