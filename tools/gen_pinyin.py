#!/usr/bin/env python3
"""Regenerates src/pinyin_table.c from pypinyin's character dictionary (first reading per character)."""
import sys
from pypinyin.pinyin_dict import pinyin_dict

syllables = sorted({readings.split(",")[0] for readings in pinyin_dict.values()})
index = {s: i for i, s in enumerate(syllables)}

out = sys.stdout
out.write("/* Generated by tools/gen_pinyin.py; do not edit. */\n")
out.write('#include "pinyin_table.h"\n\n')
out.write("const char *const pinyin_syllables[] = {\n")
for s in syllables:
    out.write(f'    "{s}",\n')
out.write("};\n\n")
out.write("const PinyinEntry pinyin_entries[] = {\n")
for cp in sorted(pinyin_dict):
    out.write(f"    {{0x{cp:X}, {index[pinyin_dict[cp].split(',')[0]]}}},\n")
out.write("};\n\n")
out.write(f"const unsigned pinyin_entry_count = {len(pinyin_dict)};\n")
